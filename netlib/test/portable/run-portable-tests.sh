#!/usr/bin/env bash
# Builds and runs the platform-independent native tests with the host C++ compiler and
# GoogleTest. The full netlib-tests suite still requires Windows (see netlib/README.md); this
# runner exists so the DNS routing policy and the real packet-rewriting code it drives can also
# be exercised on Linux/macOS CI hosts and developer machines.
#
#   * ../proxy/dns_routing_policy_test.cpp  - also part of the Windows netlib-tests project
#   * ../proxy/dns_udp_multiplexer_test.cpp - also part of the Windows netlib-tests project
#   * dns_packet_redirect_test.cpp          - portable only: compiles the production
#     tcp_local_redirect.h / socks5_udp_local_redirect.h against winshim/ and the product
#     CNdisApi checksum routines extracted verbatim from external/ndisapi/ndisapi/ndisapi.cpp
#
# Usage: netlib/test/portable/run-portable-tests.sh [extra gtest arguments]
# Requires: a C++20 compiler (CXX, default g++), GoogleTest, and the Microsoft GSL headers.
# Set SANITIZE=1 to build with AddressSanitizer and UndefinedBehaviorSanitizer.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../../.." && pwd)"
out="${PORTABLE_TEST_OUT:-$(mktemp -d)}"
cxx="${CXX:-g++}"
mkdir -p "$out"

flags=(-std=c++20 -O1 -g -Wall -Wextra -Werror -Wno-unknown-pragmas -pthread)
if [[ "${SANITIZE:-0}" == "1" ]]; then
  # Packet headers follow the 14-byte Ethernet header, so netlib (like the driver API) accesses
  # in_addr fields at 2-byte alignment by design; x86 and ARM64 permit this.
  flags+=(-fsanitize=address,undefined -fno-sanitize=alignment -fno-omit-frame-pointer)
fi

# Product checksum routines, extracted verbatim so the packet tests verify the shipped code.
ndisapi_cpp="$repo/external/ndisapi/ndisapi/ndisapi.cpp"
if [[ ! -f "$ndisapi_cpp" ]]; then
  echo "external/ndisapi is not checked out; run: git submodule update --init" >&2
  exit 1
fi
checksums="$out/ndisapi_checksums.cpp"
{
  echo '// Generated by run-portable-tests.sh from external/ndisapi/ndisapi/ndisapi.cpp. Do not edit.'
  echo '#include "winshim/packet_env.h"'
  awk '/^void CNdisApi::Recalculate(IP|TCP|UDP)Checksum\(/{p=1} p{print} p&&/^}/{p=0; print ""}' \
    "$ndisapi_cpp"
} > "$checksums"
if [[ "$(grep -c '^void CNdisApi::Recalculate' "$checksums")" != "3" ]]; then
  echo "Failed to extract the CNdisApi checksum routines from external/ndisapi/ndisapi/ndisapi.cpp" >&2
  exit 1
fi

"$cxx" "${flags[@]}" -I"$here" -I"$here/winshim" \
  "$here/../proxy/dns_routing_policy_test.cpp" \
  "$here/../proxy/dns_udp_multiplexer_test.cpp" \
  "$here/dns_packet_redirect_test.cpp" \
  "$checksums" \
  -lgtest -lgtest_main \
  -o "$out/netlib-portable-tests"

"$out/netlib-portable-tests" "$@"
